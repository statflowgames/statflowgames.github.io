// 월드마다 자주 나오는 조각 종류
const TAGW = [
  { slope: 1.6, flat: 1.2 },
  { slope: 1.8, spike: 1.5, speed: 1.4 },
  { flat: 1.4, enemy: 1.4, slope: 1.3 },
  { spike: 2.2, pit: 1.5, stairs: 1.4 },
  { pit: 2.2, spring: 2.4 },
];
function pickChunk(r, maxTier, w, last) {
  const cand = [];
  let tot = 0;
  for (const c of POOL) {
    if (c.tier > maxTier || c.name === last) continue;
    if (c.name === 'beepit' && w < 4 && maxTier < 3) continue;
    let wt = 1;
    for (const tg of c.tags) wt *= TAGW[w][tg] || 1;
    if (c.tier === maxTier) wt *= 1.6;
    cand.push([c, wt]); tot += wt;
  }
  let x = r() * tot;
  for (const [c, wt] of cand) { x -= wt; if (x <= 0) return c; }
  return cand[cand.length - 1][0];
}
function boxContent(r) {
  const x = r();
  return x < 0.64 ? 'acorns' : x < 0.76 ? 'shield' : x < 0.88 ? 'chili' : 'magnet';
}

class Level {
  constructor(world, cap) {
    this.world = world; this.cap = cap; this.w = 0;
    this.t = new Uint8Array(cap * ROWS);
    this.objs = []; this.box = new Map();
    this.start = null; this.goalX = 1e9; this.endless = false; this.par = 60;
  }
  get(tx, ty) {
    if (ty < 0 || ty >= ROWS) return 0;
    if (tx < 0) return 9;
    if (tx >= this.w) return this.endless ? 0 : 9;
    return this.t[tx * ROWS + ty];
  }
  set(tx, ty, v) { if (tx >= 0 && tx < this.w && ty >= 0 && ty < ROWS) this.t[tx * ROWS + ty] = v; }
  addFlat(n) {
    if (this.w + n > this.cap) return;
    for (let c = 0; c < n; c++) for (let ty = ROWS - 3; ty < ROWS; ty++) this.t[(this.w + c) * ROWS + ty] = 1;
    this.w += n;
  }
  addChunk(ch, r, boxFn) {
    const H = ch.rows.length, off = ROWS - H, x0 = this.w, out = [];
    if (x0 + ch.w > this.cap) return null;
    for (let i = 0; i < H; i++) {
      const row = ch.rows[i], ty = i + off;
      for (let c = 0; c < ch.w; c++) {
        const k = row[c], tx = x0 + c, px = tx * T + T / 2, py = ty * T + T / 2, foot = (ty + 1) * T;
        let v = 0;
        switch (k) {
          case '#': v = 1; break;
          case '/': v = 2; break;
          case '\\': v = 3; break;
          case 'B': v = 4; break;
          case '?': v = 5; this.box.set(tx * ROWS + ty, boxFn ? boxFn(r) : boxContent(r)); break;
          case '=': v = 7; break;
          case '^': v = 8; break;
          case 'X': v = 9; break;
          case 'o': out.push({ k: 'acorn', x: px, y: py }); break;
          case '*': out.push({ k: 'starspot', x: px, y: py }); break;
          case 'S': out.push({ k: 'spring', x: px, y: foot }); break;
          case '>': out.push({ k: 'pad', x: px, y: foot, d: 1 }); break;
          case '<': out.push({ k: 'pad', x: px, y: foot, d: -1 }); break;
          case 'e': out.push({ k: 'enemy', type: 'beetle', x: px, y: foot }); break;
          case 'k': out.push({ k: 'enemy', type: 'spiky', x: px, y: foot }); break;
          case 'f': out.push({ k: 'enemy', type: 'bee', x: px, y: foot }); break;
          case 'h': out.push({ k: 'enemy', type: 'frog', x: px, y: foot }); break;
          case 'P': this.start = { x: px, y: foot }; break;
          case 'G': this.goalX = px; out.push({ k: 'goal', x: px, y: foot }); break;
          case 'C': out.push({ k: 'check', x: px, y: foot }); break;
          default:
            if (k >= '1' && k <= '9') out.push({ k: 'sign', x: px, y: foot, text: 'tut' + k });
        }
        this.t[tx * ROWS + ty] = v;
      }
    }
    this.w += ch.w;
    return out;
  }
}

// 별 조각 3개를 스테이지 앞·중간·뒤에 하나씩 고른다
function placeStars(L, r) {
  const spots = L.objs.filter(o => o.k === 'starspot').sort((a, b) => a.x - b.x);
  let chosen = [];
  const n = spots.length;
  if (n >= 3) {
    const a = Math.floor(n / 3), b = Math.floor((2 * n) / 3);
    chosen = [spots[Math.floor(r() * a)], spots[a + Math.floor(r() * (b - a))], spots[b + Math.floor(r() * (n - b))]];
  } else {
    chosen = spots.slice();
    const ac = L.objs.filter(o => o.k === 'acorn').sort((a, b) => a.x - b.x);
    let q = 0;
    while (chosen.length < 3 && ac.length) {
      const i = Math.min(ac.length - 1, Math.floor(ac.length * ((q++ + 0.5) / 3)));
      chosen.push(ac.splice(i, 1)[0]);
    }
  }
  for (const o of L.objs) if (o.k === 'starspot') o.k = 'acorn';
  chosen.sort((a, b) => a.x - b.x).forEach((o, i) => { o.k = 'star'; o.i = i; });
}

function genStage(w, s) {
  const r = mulberry(7919 + w * 1013 + s * 131);
  const L = new Level(w, 1400);
  L.objs.push(...L.addChunk(CH.start, r));
  const seq = [];
  if (w === 0 && s === 0) {
    seq.push('tut1', 'tut2', 'tut3', 'tut4', 'hill', 'check', 'tut5', 'hill2', 'tut6', 'flat');
  } else {
    const n = 6 + s + w * 2;
    const maxTier = Math.min(3, Math.floor((w * STAGES_PER_WORLD + s + 3) / 5));
    let last = null;
    for (let i = 0; i < n; i++) { const c = pickChunk(r, maxTier, w, last); seq.push(c.name); last = c.name; }
    seq.splice(Math.floor(n / 2), 0, 'check');
  }
  const tutBox = r2 => (r2() < 0.5 ? 'shield' : 'acorns');
  for (const name of seq) {
    if (name !== 'check' && r() < 0.55) L.addFlat(1 + Math.floor(r() * 3));
    L.objs.push(...L.addChunk(CH[name], r, w === 0 && s === 0 ? tutBox : null));
  }
  L.addFlat(2);
  L.objs.push(...L.addChunk(CH.goal, r));
  L.addFlat(32);
  placeStars(L, r);
  L.par = Math.round(((L.goalX - L.start.x) / 228) + 3);
  return L;
}

function newEndlessLevel() {
  const L = new Level(0, 40000);
  L.endless = true;
  const r = mulberry(1);
  L.addChunk(CH.start, r);
  L.addFlat(10);
  return L;
}
