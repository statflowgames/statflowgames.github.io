const TILE = { EMPTY: 0, GROUND: 1, UP: 2, DOWN: 3, BRICK: 4, BOX: 5, USED: 6, ONEWAY: 7, SPIKE: 8, STONE: 9 };
const CH = {};
const POOL = [];
function chunk(name, tier, tags, src, special) {
  const rows = src.split('\n').map(s => s.trim()).filter(s => s.length);
  const w = Math.max(...rows.map(r => r.length));
  const c = { name, tier, tags, rows: rows.map(r => r.padEnd(w, '.')), w };
  CH[name] = c;
  if (!special) POOL.push(c);
  return c;
}

